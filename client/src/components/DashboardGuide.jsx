import { useState } from 'react';

function DashboardGuide() {
  const [open, setOpen] = useState(true);

  return (
    <section className="card dashboard-guide">
      <button
        type="button"
        className="dashboard-guide__toggle"
        onClick={() => setOpen(!open)}
        aria-expanded={open}
      >
        <h2>Как пользоваться панелью управления</h2>
        <span className="dashboard-guide__icon">{open ? '−' : '+'}</span>
      </button>

      {open && (
        <div className="dashboard-guide__content">
          <ol className="dashboard-guide__steps">
            <li>
              <strong>Добавление груза</strong> — нажмите «+ Добавить груз», заполните форму
              (название, вес, города отправления и назначения) и сохраните. Новая запись появится в
              таблице.
            </li>
            <li>
              <strong>Обработка заказа</strong> — в блоке справа выберите груз со статусом
              «Ожидает» и нажмите «Запустить цепочку». Система рассчитает маршрут, проверит
              накладную и назначит свободного водителя.
            </li>
            <li>
              <strong>Назначение водителя вручную</strong> — сначала выберите груз в списке
              «Обработка заказа», затем нажмите «Назначить» у нужного водителя.
            </li>
            <li>
              <strong>Оптимизация маршрута</strong> — укажите города (Минск, Гомель, Бобруйск и
              др.), при необходимости добавьте промежуточные точки через запятую и нажмите
              «Рассчитать маршрут».
            </li>
            <li>
              <strong>Отслеживание груза</strong> — после выбора груза внизу появится карта.
              Отслеживание работает для грузов «В пути» и «Доставлен». Нажмите «Обновить» для
              ручного обновления позиции.
            </li>
            <li>
              <strong>Журнал заправок и ТО</strong> — заполните поля в блоке «Управление
              водителями» и сохраните запись о заправке или техобслуживании.
            </li>
            <li>
              <strong>Удаление</strong> — в таблице нажмите «Удалить» напротив ненужной записи.
            </li>
          </ol>
          <p className="dashboard-guide__tip">
            Совет: для полного цикла выберите груз «Ожидает» → «Запустить цепочку» → дождитесь
            статуса «В пути» → отслеживайте на карте внизу страницы.
          </p>
        </div>
      )}
    </section>
  );
}

export default DashboardGuide;
